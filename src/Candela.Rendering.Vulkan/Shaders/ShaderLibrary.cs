using System.Collections.Concurrent;
using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using Candela.Photometry;

namespace Candela.Rendering.Vulkan;

/// <summary>
/// GLSL sources: the files embedded from <c>Shaders/</c> plus one generated include, <c>generated.glsl</c>, that
/// carries constants owned by C# (descriptor bindings, cluster grid size, colour matrices from
/// <see cref="ColorSpaces"/>) so the two sides cannot drift apart. Setting <c>CANDELA_SHADER_DIR</c> to the source
/// folder makes the library read files from disk first (shader development without rebuilding).
/// </summary>
internal sealed partial class ShaderLibrary
{
    /// <summary>Name of the generated include.</summary>
    public const string GeneratedInclude = "generated.glsl";

    private const string ResourcePrefix = "Shaders/";
    private static readonly Lazy<ShaderLibrary> _default = new(() => new ShaderLibrary(Environment.GetEnvironmentVariable("CANDELA_SHADER_DIR")));
    private readonly Assembly _assembly = typeof(ShaderLibrary).Assembly;
    private readonly string? _overrideDirectory;
    // Shared by every renderer of the process (Default), possibly on several threads at once.
    private readonly ConcurrentDictionary<string, string> _cache = new(StringComparer.Ordinal);

    public ShaderLibrary(string? overrideDirectory)
    {
        _overrideDirectory = string.IsNullOrWhiteSpace(overrideDirectory) ? null : overrideDirectory;
        Generated = BuildGenerated();
    }

    /// <summary>The shared library (embedded sources, optional override directory from the environment).</summary>
    public static ShaderLibrary Default => _default.Value;

    /// <summary>Text of <c>generated.glsl</c>.</summary>
    public string Generated { get; }

    /// <summary>Shader stage files (vert/frag/comp) embedded in the assembly.</summary>
    public IReadOnlyList<string> StageFiles =>
        _assembly.GetManifestResourceNames()
            .Where(n => n.StartsWith(ResourcePrefix, StringComparison.Ordinal))
            .Select(n => n[ResourcePrefix.Length..])
            .Where(n => n.EndsWith(".vert", StringComparison.Ordinal) || n.EndsWith(".frag", StringComparison.Ordinal) ||
                        n.EndsWith(".comp", StringComparison.Ordinal))
            .OrderBy(n => n, StringComparer.Ordinal)
            .ToList();

    /// <summary>Source of a file (stage file or include), or null when it does not exist.</summary>
    public string? TryGetSource(string name)
    {
        if (name == GeneratedInclude)
            return Generated;
        if (_cache.TryGetValue(name, out var cached))
            return cached;
        string? text = null;
        if (_overrideDirectory is not null)
        {
            string path = Path.Combine(_overrideDirectory, name);
            if (File.Exists(path))
                text = File.ReadAllText(path);
        }

        if (text is null)
        {
            using var stream = _assembly.GetManifestResourceStream(ResourcePrefix + name);
            if (stream is null)
                return null;
            using var reader = new StreamReader(stream, Encoding.UTF8);
            text = reader.ReadToEnd();
        }

        if (_overrideDirectory is null)
            _cache.TryAdd(name, text); // embedded sources never change; files on disk are re-read for hot reload
        return text;
    }

    /// <summary>Source of a file; throws when missing.</summary>
    public string GetSource(string name) => TryGetSource(name) ?? throw new FileNotFoundException($"Shader source '{name}' not found.");

    /// <summary>Names of the files <paramref name="name"/> includes, transitively (sorted, without the file itself).</summary>
    public IReadOnlyList<string> IncludeClosure(string name)
    {
        var seen = new SortedSet<string>(StringComparer.Ordinal);
        var stack = new Stack<string>();
        stack.Push(name);
        while (stack.Count > 0)
        {
            string current = stack.Pop();
            string? source = TryGetSource(current);
            if (source is null)
                continue;
            foreach (Match m in IncludeRegex().Matches(source))
            {
                string included = m.Groups[1].Value;
                if (seen.Add(included))
                    stack.Push(included);
            }
        }

        return seen.ToList();
    }

    [GeneratedRegex("^\\s*#\\s*include\\s+[\"<]([^\">]+)[\">]", RegexOptions.Multiline)]
    private static partial Regex IncludeRegex();

    private static string BuildGenerated()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by Candela.Rendering.Vulkan.ShaderLibrary — constants shared with C#.");
        sb.AppendLine("#ifndef CANDELA_GENERATED_GLSL");
        sb.AppendLine("#define CANDELA_GENERATED_GLSL");
        foreach (var (name, value) in ShaderConstants.Defines)
            sb.Append("#define ").Append(name).Append(' ').AppendLine(value);
        AppendMatrix(sb, "REC709_TO_REC2020", ColorSpaces.Rec709ToRec2020Matrix);
        AppendMatrix(sb, "REC2020_TO_REC709", ColorSpaces.Rec2020ToRec709Matrix);
        var y = ColorSpaces.Rec2020LuminanceCoefficients;
        sb.AppendLine(CultureInfo.InvariantCulture, $"const vec3 REC2020_LUMINANCE = vec3({F(y.X)}, {F(y.Y)}, {F(y.Z)});");
        sb.AppendLine("#endif");
        return sb.ToString();
    }

    private static void AppendMatrix(StringBuilder sb, string name, ColorMatrix3 m)
    {
        // GLSL mat3 constructors take columns; ColorMatrix3 rows map RGB → RGB as row · rgb.
        sb.AppendLine(CultureInfo.InvariantCulture,
            $"const mat3 {name} = mat3({F(m.M11)}, {F(m.M21)}, {F(m.M31)}, {F(m.M12)}, {F(m.M22)}, {F(m.M32)}, {F(m.M13)}, {F(m.M23)}, {F(m.M33)});");
    }

    private static string F(float v) => v.ToString("0.000000000", CultureInfo.InvariantCulture);
}

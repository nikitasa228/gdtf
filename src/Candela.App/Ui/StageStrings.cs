/// <summary>
/// English and Russian texts of <see cref="StageStr"/>, following <see cref="Loc.Language"/>. <see cref="Get"/> is an
/// array lookup (no allocation); <see cref="With"/> caches "icon  text" labels per language. Strings with placeholders
/// use <see cref="string.Format(IFormatProvider, string, object[])"/> syntax.
/// </summary>
internal static class StageLoc
{
    private static readonly string[] English;
    private static readonly string[] Russian;
    private static readonly Dictionary<(string Icon, StageStr Key), string> s_labels = new();
    private static string s_labelsLanguage = "";

    static StageLoc()
    {
        int n = Enum.GetValues<StageStr>().Length;
        English = new string[n];
        Russian = new string[n];
        foreach (var (key, en, ru) in Table)
        {
            English[(int)key] = en;
            Russian[(int)key] = ru;
        }

        for (int i = 0; i < n; i++)
            English[i] ??= ((StageStr)i).ToString();
    }

    /// <summary>The text of <paramref name="key"/> in the current UI language (English when untranslated).</summary>
    public static string Get(StageStr key)
    {
        int i = (int)key;
        if ((uint)i >= (uint)English.Length)
            return key.ToString();
        return Loc.Language == "ru" && Russian[i] is { Length: > 0 } ru ? ru : English[i];
    }

    /// <summary>Formats the text of <paramref name="key"/> (culture-invariant numbers).</summary>
    public static string Format(StageStr key, params object?[] args) => string.Format(CultureInfo.InvariantCulture, Get(key), args);

    /// <summary>"icon  text" for headers, tabs and buttons, built once per language.</summary>
    public static string With(string icon, StageStr key)
    {
        if (!string.Equals(s_labelsLanguage, Loc.Language, StringComparison.Ordinal))
        {
            s_labels.Clear();
            s_labelsLanguage = Loc.Language;
        }

        if (!s_labels.TryGetValue((icon, key), out var label))
        {
            label = icon.Length > 0 ? icon + "  " + Get(key) : Get(key);
            s_labels[(icon, key)] = label;
        }

        return label;
    }

    /// <summary>The protocol's description in the UI language.</summary>
    public static string ProtocolDescription(ProtocolDescriptor descriptor) =>
        Loc.Language == "ru" && RussianProtocols.TryGetValue(descriptor.Id, out var ru) ? ru.Description : descriptor.Description;

    /// <summary>Why the protocol has its support level, in the UI language.</summary>
    public static string ProtocolSupportReason(ProtocolDescriptor descriptor) =>
        Loc.Language == "ru" && RussianProtocols.TryGetValue(descriptor.Id, out var ru) ? ru.Reason : descriptor.SupportReason;


using System.Numerics;
using Candela.Core.Math;

namespace Candela.Core.Geometry;

/// <summary>
/// CPU-side triangle mesh exchanged between importers (GDTF 3DS/glTF, Assimp), procedural generators (walls, trusses,
/// cables) and the renderer. Positions in metres, counter-clockwise front faces, Z up.
/// </summary>
public sealed class MeshData
{
    public string Name { get; set; } = "";
    public Vector3[] Positions { get; set; } = Array.Empty<Vector3>();
    public Vector3[] Normals { get; set; } = Array.Empty<Vector3>();

    /// <summary>Texture coordinates (optional, same length as positions when present).</summary>
    public Vector2[]? TexCoords { get; set; }

    /// <summary>xyz = tangent, w = bitangent sign (optional; generated by the renderer when missing).</summary>
    public Vector4[]? Tangents { get; set; }

    public uint[] Indices { get; set; } = Array.Empty<uint>();

    /// <summary>Index ranges drawn with one material each. Empty = the whole mesh uses slot 0.</summary>
    public List<SubMesh> SubMeshes { get; set; } = new();

    public int VertexCount => Positions.Length;
    public int TriangleCount => Indices.Length / 3;

    public Aabb ComputeBounds()
    {
        var b = Aabb.Empty;
        foreach (var p in Positions) b.Include(p);
        return b;
    }

    /// <summary>Area-weighted smooth normals (used when a file has none).</summary>
    public void ComputeNormals()
    {
        var n = new Vector3[Positions.Length];
        for (int i = 0; i + 2 < Indices.Length; i += 3)
        {
            uint a = Indices[i], b = Indices[i + 1], c = Indices[i + 2];
            var fn = Vector3.Cross(Positions[b] - Positions[a], Positions[c] - Positions[a]);
            n[a] += fn;
            n[b] += fn;
            n[c] += fn;
        }
        for (int i = 0; i < n.Length; i++)
            n[i] = n[i].LengthSquared() > 1e-20f ? Vector3.Normalize(n[i]) : Vector3.UnitZ;
        Normals = n;
    }

    /// <summary>Checks array lengths and index bounds; throws with a readable message.</summary>
    public void Validate()
    {
        if (Normals.Length != Positions.Length) throw new InvalidDataException($"Mesh '{Name}': {Normals.Length} normals for {Positions.Length} positions.");
        if (TexCoords is not null && TexCoords.Length != Positions.Length) throw new InvalidDataException($"Mesh '{Name}': texcoord count mismatch.");
        if (Tangents is not null && Tangents.Length != Positions.Length) throw new InvalidDataException($"Mesh '{Name}': tangent count mismatch.");
        if (Indices.Length % 3 != 0) throw new InvalidDataException($"Mesh '{Name}': index count is not a multiple of 3.");
        foreach (var i in Indices)
            if (i >= Positions.Length) throw new InvalidDataException($"Mesh '{Name}': index {i} out of range.");
    }
}

public readonly record struct SubMesh(int IndexStart, int IndexCount, int MaterialSlot);

/// <summary>
/// A model: parts (mesh + local transform + material slot mapping) and materials. Used for imported files and
/// GDTF geometry models.
/// </summary>
public sealed class ModelData
{
    public string Name { get; set; } = "";
    public List<ModelPart> Parts { get; set; } = new();
    public List<MaterialData> Materials { get; set; } = new();

    public Aabb ComputeBounds()
    {
        var b = Aabb.Empty;
        foreach (var p in Parts) b.Include(p.Mesh.ComputeBounds().Transform(p.Transform));
        return b;
    }
}

public sealed class ModelPart
{
    public string Name { get; set; } = "";
    public MeshData Mesh { get; set; } = new();
    public Matrix4x4 Transform { get; set; } = Matrix4x4.Identity;
}

public enum AlphaMode
{
    Opaque,
    Mask,
    Blend,
}

/// <summary>
/// PBR metallic-roughness material (glTF semantics). Factors are linear Rec.709 as in glTF; colour textures are
/// sRGB-encoded; the renderer converts to the Rec.2020 working space. Texture fields are keys resolved by an
/// <see cref="IImageSource"/> (e.g. "asset:{guid}/wood.png", "gdtf:{file}#models/gltf/tex.png", "builtin:concrete/albedo").
/// </summary>
public sealed class MaterialData
{
    public string Name { get; set; } = "";
    public Vector4 BaseColorFactor { get; set; } = Vector4.One;
    public float Metallic { get; set; }
    public float Roughness { get; set; } = 0.6f;

    /// <summary>Emitted luminance in cd/m² for a white emissive colour of 1 (LED screens, practicals).</summary>
    public float EmissiveLuminance { get; set; }

    public Vector3 EmissiveColor { get; set; } = Vector3.One;
    public AlphaMode AlphaMode { get; set; } = AlphaMode.Opaque;
    public float AlphaCutoff { get; set; } = 0.5f;
    public bool DoubleSided { get; set; }

    /// <summary>Index of refraction for transmissive materials (glass ≈ 1.5).</summary>
    public float Ior { get; set; } = 1.5f;

    /// <summary>0 = opaque surface, 1 = fully transmissive (glass).</summary>
    public float Transmission { get; set; }

    public string? BaseColorTexture { get; set; }
    public string? NormalTexture { get; set; }
    public string? MetallicRoughnessTexture { get; set; }
    public string? OcclusionTexture { get; set; }
    public string? EmissiveTexture { get; set; }

    /// <summary>Scale applied to texture coordinates.</summary>
    public Vector2 UvScale { get; set; } = Vector2.One;
}

public enum PixelFormat
{
    /// <summary>8-bit RGBA, sRGB-encoded colour or linear data depending on use.</summary>
    Rgba8,

    /// <summary>32-bit float RGBA, linear.</summary>
    RgbaFloat,
}

/// <summary>Decoded image (top row first).</summary>
public sealed class ImageData
{
    public int Width { get; init; }
    public int Height { get; init; }
    public PixelFormat Format { get; init; } = PixelFormat.Rgba8;

    /// <summary>Rgba8: 4 bytes per pixel. RgbaFloat: 16 bytes per pixel (little-endian floats).</summary>
    public byte[] Pixels { get; init; } = Array.Empty<byte>();
}

/// <summary>Resolves texture keys (see <see cref="MaterialData"/>) to decoded images.</summary>
public interface IImageSource
{
    ImageData? Load(string key);
}
